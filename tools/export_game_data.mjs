#!/usr/bin/env node
/**
 * Exports the game facts the server needs to check online play (M11): landmark positions (world
 * px, from map cells) and the danfo routes. The server never trusts positions or routes sent by
 * a client; it checks them against this file.
 *   node tools/export_game_data.mjs   →   apps/server/src/game_data.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const CELL = 64;
const map = JSON.parse(readFileSync('game/data/map/lagos.json', 'utf8'));
const jobs = JSON.parse(readFileSync('game/data/jobs.json', 'utf8'));
const landmarks = {};
for (const l of map.landmarks) {
  landmarks[l.id] = { x: l.cell[0] * CELL + CELL / 2, y: l.cell[1] * CELL + CELL / 2, district: l.district, name: l.name };
}
const routes = jobs.danfo_routes.map((r) => ({ id: r.id, name: r.name, from: r.from, to: r.to, fare: r.fare }));
const out = `// Generated by tools/export_game_data.mjs from game/data. Do not edit by hand.
export interface Landmark { x: number; y: number; district: string; name: string }
export const LANDMARKS: Record<string, Landmark> = ${JSON.stringify(landmarks, null, 2)};
export interface Route { id: string; name: string; from: string; to: string; fare: number }
export const ROUTES: Route[] = ${JSON.stringify(routes, null, 2)};
`;
writeFileSync('apps/server/src/game_data.ts', out);
console.log(`landmarks ${Object.keys(landmarks).length}, routes ${routes.length}`);
